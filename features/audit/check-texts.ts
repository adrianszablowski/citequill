export interface CheckText {
    name: string;
    says: string;
    link: string;
    fix: string;
}

export const severityNames: Record<Severity, string> = {
    '3': 'Critical',
    '2': 'Major',
    '1': 'Minor',
    hint: 'Hint',
    question: 'Question',
};

export const areaNames: Record<Area, string> = {
    indexability: 'Indexability',
    'on-page': 'On-page',
    links: 'Links',
    https: 'HTTPS',
    mobile: 'Mobile',
    performance: 'Performance',
    'ai-access': 'AI access',
};

export const notCounted = 'Google does not count this.';

export const notScored = 'Citequill does not count this in the score.';

export function checkText(id: CheckId) {
    const text = texts[id];

    if (!text) {
        return null;
    }

    const { area, severity } = checkOf(id);

    return severity === 'hint'
        ? {
              ...text,
              says: `${text.says} ${area === 'ai-access' ? notScored : notCounted}`,
          }
        : text;
}

